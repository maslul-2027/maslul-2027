'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const html=fs.readFileSync('preview/index.html','utf8');
const manifest=JSON.parse(fs.readFileSync('preview/manifest.webmanifest','utf8'));
const sw=fs.readFileSync('preview/sw.js','utf8');
const inventory=JSON.parse(fs.readFileSync('preview/capabilities.json','utf8'));
assert.match(html,/<html lang="he" dir="rtl">/);
assert.doesNotMatch(html,/<iframe\b/i,'No embedded second application');
assert.doesNotMatch(html,/const names=\[|const people=names\.map|WF_KEY|const tasks=\[\{name:/,'No parallel demo roster, fitness, or tasks');
const nav=html.match(/<nav class="mobile-bottom-nav"[^>]*>[\s\S]*?<\/nav>/);
assert.ok(nav,'Bottom navigation must exist');
assert.equal((nav[0].match(/data-mobile-route="/g)||[]).length,4);
for(const tab of ['dash','soldiers','attendance','more'])assert.match(nav[0],new RegExp('data-mobile-route="'+tab+'"'));
for(const id of ['view','side','grps','menuBtn','course','stageNotice'])assert.match(html,new RegExp('id="'+id+'"'));
assert.match(html,/course-engine\.js/,'All original APIs come from the shared engine');
assert.match(html,/google\.script\.run/,'Original service bridge retained');
assert.match(html,/navigator\.serviceWorker\.register/);
assert.match(html,/הדגמה סינתטית/);
assert.doesNotMatch(html,/script\.google\.com\/macros|AKfycb[A-Za-z0-9_-]+|BEGIN PRIVATE KEY|client_secret/);
assert.equal(manifest.display,'standalone');assert.equal(manifest.dir,'rtl');assert.equal(manifest.lang,'he');
assert.ok(manifest.icons.some(icon=>fs.existsSync('preview/'+icon.src.replace('./',''))));
assert.ok(sw.includes('mobile-shell.css'));
assert.ok(fs.existsSync('preview/mobile-shell.css'));
const methods=Object.values(inventory.groups).flat();assert.equal(methods.length,174);
assert.equal(new Set(methods).size,174);
console.log('PASS: single app, 174 APIs inventoried, synthetic only, accessible 4-button navigation, no iframe/shadow data');
