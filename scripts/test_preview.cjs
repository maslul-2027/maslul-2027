'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const html=fs.readFileSync('preview/index.html','utf8'),engine=fs.readFileSync('preview/engine.js','utf8');
const manifest=JSON.parse(fs.readFileSync('preview/manifest.webmanifest','utf8'));
const sw=fs.readFileSync('preview/sw.js','utf8');
const inventory=JSON.parse(fs.readFileSync('preview/capabilities.json','utf8'));
assert.match(html,/<html lang="he" dir="rtl">/);
assert.doesNotMatch(html,/<iframe\b/i,'No embedded second application');
assert.doesNotMatch(html,/const names=\[|const people=names\.map|WF_KEY|const tasks=\[\{name:|id="side"|id="grps"/,'No legacy/parallel demo DOM or data');
const nav=html.match(/<nav class="nav" aria-label="ניווט ראשי">[\s\S]*?<\/nav>/);assert.ok(nav,'bottom nav');
assert.equal((nav[0].match(/class="tab"/g)||[]).length,4);
for(const t of['home','soldiers','tasks','more'])assert.match(nav[0],new RegExp('data-go="'+t+'"'));
for(const l of['בית','חניכים','מעקבים','עוד'])assert.ok(nav[0].includes(l+'</button>'),l);
assert.match(html,/MASLUL <b>2027<\/b>/);assert.match(html,/DEMO · נתונים לדוגמה/);
assert.match(html,/src="\.\/engine\.js"/);assert.match(engine,/window\.appClient=client/);
assert.doesNotMatch(html,/localStorage/,'UI never keeps its own data');
assert.match(html,/navigator\.serviceWorker\.register\('\.\/sw\.js',\{updateViaCache:'none'\}\)/);
assert.match(html,/טרם חובר להדגמה|נשמרים במכשיר הזה בלבד/);assert.match(html,/id: 'refresh-app'/);assert.match(html,/registration\?\.update\(\)/);assert.match(html,/location\.replace\(url\)/);assert.match(html,/איפוס הדגמה/);
assert.match(engine,/טרם חובר להדגמה/);
assert.doesNotMatch(html+engine,/script\.google\.com\/macros|AKfycb[A-Za-z0-9_-]+|BEGIN PRIVATE KEY|client_secret/);
assert.equal(manifest.display,'standalone');assert.equal(manifest.dir,'rtl');assert.equal(manifest.lang,'he');
assert.ok(manifest.icons.some(i=>fs.existsSync('preview/'+i.src.replace('./',''))));
assert.ok(sw.includes('engine.js'));
const methods=Object.values(inventory.groups).flat();assert.equal(methods.length,174);assert.equal(new Set(methods).size,174);
console.log('PASS: native PR#10 shell, 4 tabs, one appClient data layer, 174 APIs inventoried, synthetic only, no iframe');
